    enum class Ownership { FEDERAL, STATE, PRIVATE }

    data class University(
        val id: String,
        val name: String,
        val ownership: Ownership,
        val state: String,
    )

    private fun stableId(name: String): String =
        "ng-university:" + name.lowercase(java.util.Locale.ROOT)
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')

