import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const app=readFileSync('web/app.js','utf8');
const styles=readFileSync('web/styles.css','utf8');
const initStart=app.indexOf('async function init(){');
assert.notEqual(initStart,-1);
const init=app.slice(initStart);
assert.match(init,/location\.pathname!=='\/'[\s\S]*?scheduleServiceWorkerRegistration\(\)/,'public homepage must survive missing app credentials');
const ms=app.indexOf('async function renderMessages(path){');
const me=app.indexOf('async function renderGroupInvitations(){',ms);
assert.ok(ms>=0&&me>ms);
const messages=app.slice(ms,me);
assert.doesNotMatch(messages,/get_my_unread_message_notifications/,'unread alerts must not masquerade as a full inbox');
assert.match(messages,/Full inbox temporarily unavailable/);
assert.match(app,/const rollback=\(\)=>\{[\s\S]*?el\.dataset\.wasUnread='1'[\s\S]*?el\.classList\.add\('unread'\)/,'failed read writes must roll back');
assert.match(app,/data-media-image/);
assert.match(app,/Image unavailable/);
assert.match(app,/Promise\.allSettled\(\[/,'people and post search must fail independently');
assert.match(app,/People search unavailable/);
assert.match(app,/Post search unavailable/);
assert.match(styles,/\.post-media \.media-unavailable/);
console.log('Web release-audit regression contracts passed.');
