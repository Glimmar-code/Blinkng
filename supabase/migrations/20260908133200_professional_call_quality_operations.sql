create or replace function public.start_call(
  p_conversation_id uuid,
  p_callee_id uuid,
  p_call_type text
)
returns public.calls
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_caller_id uuid := auth.uid();
  v_call public.calls;
begin
  if v_caller_id is null then raise exception 'AUTHENTICATION_REQUIRED'; end if;
  if p_callee_id is null or p_callee_id = v_caller_id then raise exception 'INVALID_CALLEE'; end if;
  if p_call_type not in ('audio','video') then raise exception 'INVALID_CALL_TYPE'; end if;
  if not exists (
    select 1 from public.conversation_participants cp
    where cp.conversation_id=p_conversation_id and cp.user_id=v_caller_id and cp.left_at is null and cp.can_call=true
  ) or not exists (
    select 1 from public.conversation_participants cp
    where cp.conversation_id=p_conversation_id and cp.user_id=p_callee_id and cp.left_at is null and cp.can_call=true
  ) then raise exception 'NOT_CONVERSATION_PARTICIPANT'; end if;
  if not private.chat_scope_allows(v_caller_id,p_callee_id,'call') then raise exception 'CALL_PRIVACY_BLOCKED'; end if;

  update public.calls
     set status='missed',ended_at=now(),end_reason='timeout',ended_cleanly=true
   where status='ringing' and timeout_at<=now()
     and (caller_id in (v_caller_id,p_callee_id) or callee_id in (v_caller_id,p_callee_id));

  if exists (
    select 1 from public.calls c
    where c.status in ('ringing','connecting','connected')
      and (c.caller_id in (v_caller_id,p_callee_id) or c.callee_id in (v_caller_id,p_callee_id))
  ) then raise exception 'USER_BUSY'; end if;

  insert into public.calls(conversation_id,caller_id,callee_id,call_type)
  values (p_conversation_id,v_caller_id,p_callee_id,p_call_type)
  returning * into v_call;
  return v_call;
end;
$$;

create or replace function public.start_call_v2(
  p_conversation_id uuid,
  p_callee_id uuid,
  p_call_type text,
  p_client_call_id uuid
)
returns public.calls
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_existing public.calls;
  v_created public.calls;
begin
  if v_me is null then raise exception 'AUTHENTICATION_REQUIRED'; end if;
  if p_client_call_id is null then raise exception 'CLIENT_CALL_ID_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_me::text || ':call:' || p_client_call_id::text,0));
  select * into v_existing from public.calls
  where caller_id=v_me and client_call_id=p_client_call_id limit 1;
  if found then return v_existing; end if;
  v_created := public.start_call(p_conversation_id,p_callee_id,p_call_type);
  update public.calls set client_call_id=p_client_call_id where id=v_created.id returning * into v_created;
  return v_created;
end;
$$;

create or replace function public.invite_call_participant(p_call_id uuid,p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_call public.calls;
begin
  if v_me is null then raise exception 'AUTHENTICATION_REQUIRED'; end if;
  select * into v_call from public.calls where id=p_call_id for update;
  if not found then raise exception 'CALL_NOT_FOUND'; end if;
  if v_call.caller_id <> v_me then raise exception 'CALL_HOST_REQUIRED'; end if;
  if v_call.status not in ('ringing','connecting','connected') then raise exception 'CALL_NOT_ACTIVE'; end if;
  if not exists (
    select 1 from public.conversation_participants cp
    where cp.conversation_id=v_call.conversation_id and cp.user_id=p_user_id and cp.left_at is null and cp.can_call=true
  ) then raise exception 'NOT_CONVERSATION_PARTICIPANT'; end if;
  if not private.chat_scope_allows(v_me,p_user_id,'call') then raise exception 'CALL_PRIVACY_BLOCKED'; end if;

  insert into public.call_participants(call_id,user_id,role,state,camera_enabled,updated_at)
  values (p_call_id,p_user_id,'participant','invited',v_call.call_type='video',now())
  on conflict (call_id,user_id) do update set state='invited',left_at=null,updated_at=now();
  update public.calls set is_group_call=true where id=p_call_id;
  insert into public.call_events(call_id,actor_id,event_type,metadata)
  values (p_call_id,v_me,'participant_invited',jsonb_build_object('target_user_id',p_user_id));
  return true;
end;
$$;

create or replace function public.record_call_quality_sample(
  p_call_id uuid,
  p_device_id text,
  p_connection_state text,
  p_network_type text,
  p_round_trip_ms numeric,
  p_jitter_ms numeric,
  p_packets_lost bigint,
  p_packets_received bigint,
  p_audio_bitrate_bps bigint,
  p_video_bitrate_bps bigint,
  p_frames_per_second numeric,
  p_frame_width integer,
  p_frame_height integer,
  p_frames_dropped bigint,
  p_local_candidate_type text,
  p_remote_candidate_type text,
  p_turn_used boolean,
  p_quality_score numeric,
  p_metadata jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = 'public','pg_temp'
as $$
declare
  v_me uuid := auth.uid();
  v_id bigint;
begin
  if v_me is null then raise exception 'AUTHENTICATION_REQUIRED'; end if;
  if not exists (
    select 1 from public.calls c
    where c.id=p_call_id and (c.caller_id=v_me or c.callee_id=v_me)
  ) and not exists (
    select 1 from public.call_participants cp where cp.call_id=p_call_id and cp.user_id=v_me
  ) then raise exception 'CALL_NOT_ACCESSIBLE'; end if;

  insert into public.call_quality_samples(
    call_id,user_id,device_id,connection_state,network_type,round_trip_ms,jitter_ms,
    packets_lost,packets_received,audio_bitrate_bps,video_bitrate_bps,frames_per_second,
    frame_width,frame_height,frames_dropped,local_candidate_type,remote_candidate_type,
    turn_used,quality_score,metadata
  ) values (
    p_call_id,v_me,nullif(left(coalesce(p_device_id,''),200),''),p_connection_state,p_network_type,
    greatest(coalesce(p_round_trip_ms,0),0),greatest(coalesce(p_jitter_ms,0),0),
    greatest(coalesce(p_packets_lost,0),0),greatest(coalesce(p_packets_received,0),0),
    greatest(coalesce(p_audio_bitrate_bps,0),0),greatest(coalesce(p_video_bitrate_bps,0),0),
    greatest(coalesce(p_frames_per_second,0),0),p_frame_width,p_frame_height,
    greatest(coalesce(p_frames_dropped,0),0),p_local_candidate_type,p_remote_candidate_type,
    coalesce(p_turn_used,false),greatest(0,least(coalesce(p_quality_score,0),100)),coalesce(p_metadata,'{}'::jsonb)
  ) returning id into v_id;

  update public.calls
     set last_quality_score=greatest(0,least(coalesce(p_quality_score,last_quality_score,0),100)),
         network_type=coalesce(nullif(p_network_type,''),network_type),
         turn_used=turn_used or coalesce(p_turn_used,false)
   where id=p_call_id;
  return v_id;
end;
$$;

