create or replace function public.get_call_quality_summary(p_call_id uuid)
returns table(
  sample_count bigint,
  avg_round_trip_ms numeric,
  avg_jitter_ms numeric,
  avg_quality_score numeric,
  total_packets_lost numeric,
  turn_sample_count bigint,
  reconnect_count integer
)
language plpgsql
security invoker
set search_path = 'public','pg_temp'
stable
as $$
declare
  v_me uuid := auth.uid();
begin
  if v_me is null then raise exception 'AUTHENTICATION_REQUIRED'; end if;
  if not exists (
    select 1 from public.calls c where c.id=p_call_id and (c.caller_id=v_me or c.callee_id=v_me)
  ) and not exists (
    select 1 from public.call_participants cp where cp.call_id=p_call_id and cp.user_id=v_me
  ) then raise exception 'CALL_NOT_ACCESSIBLE'; end if;
  return query
  select count(q.id),avg(q.round_trip_ms),avg(q.jitter_ms),avg(q.quality_score),sum(q.packets_lost)::numeric,
         count(q.id) filter (where q.turn_used),c.reconnect_count
  from public.calls c
  left join public.call_quality_samples q on q.call_id=c.id
  where c.id=p_call_id
  group by c.reconnect_count;
end;
$$;

create or replace function private.cleanup_stale_chat_call_ephemera()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_presence integer := 0;
  v_signals integer := 0;
  v_drafts integer := 0;
  v_missed integer := 0;
begin
  update public.calls
     set status='missed',ended_at=coalesce(ended_at,now()),end_reason=coalesce(end_reason,'timeout'),ended_cleanly=true
   where status='ringing' and timeout_at<=now();
  get diagnostics v_missed = row_count;

  delete from public.conversation_presence where expires_at < now() - interval '5 minutes';
  get diagnostics v_presence = row_count;

  delete from public.call_signals s
  using public.calls c
  where c.id=s.call_id and c.ended_at is not null and c.ended_at < now()-interval '24 hours';
  get diagnostics v_signals = row_count;

  delete from public.conversation_drafts
  where updated_at < now()-interval '30 days' and content='';
  get diagnostics v_drafts = row_count;

  update public.call_push_dispatches
     set next_attempt_at=coalesce(next_attempt_at,now()+interval '5 minutes'),
         dead_letter_at=case when attempts>=5 then coalesce(dead_letter_at,now()) else dead_letter_at end,
         updated_at=now()
   where status='failed' and dead_letter_at is null;

  update public.message_push_dispatches
     set next_attempt_at=coalesce(next_attempt_at,now()+interval '5 minutes'),
         dead_letter_at=case when attempts>=5 then coalesce(dead_letter_at,now()) else dead_letter_at end,
         updated_at=now()
   where status='failed' and dead_letter_at is null;

  return jsonb_build_object('missed_calls',v_missed,'presence_deleted',v_presence,'signals_deleted',v_signals,'empty_drafts_deleted',v_drafts);
end;
$$;

