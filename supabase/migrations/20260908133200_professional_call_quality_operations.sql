-- Run stale ringing/presence/signaling cleanup every five minutes when pg_cron is present.
do $$
begin
  if exists (select 1 from pg_extension where extname='pg_cron')
     and not exists (select 1 from cron.job where jobname='blink-chat-call-ephemera-cleanup') then
    perform cron.schedule(
      'blink-chat-call-ephemera-cleanup',
      '*/5 * * * *',
      'select private.cleanup_stale_chat_call_ephemera();'
    );
  end if;
end $$;
