// Disposable database only: prove direct RPC privileges are revoked without
// disabling the trigger pathways used by authorized Marketplace operations.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
try {
  await db.exec(`
    create role anon nologin;
    create role authenticated nologin;
    create table public.market_guard_fixture(
      id integer generated by default as identity primary key,
      allowed boolean not null
    );
    grant usage on schema public to authenticated;
    grant insert, select on public.market_guard_fixture to authenticated;
    grant usage, select on sequence public.market_guard_fixture_id_seq to authenticated;
    create function public.market_require_approved_seller()
    returns trigger language plpgsql security definer set search_path=''
    as $$
    begin
      if not new.allowed then raise exception 'SELLER_NOT_APPROVED'; end if;
      return new;
    end;
    $$;
    create function public.market_require_approved_seller_for_order()
    returns trigger language plpgsql security definer set search_path=''
    as $$
    begin
      if not new.allowed then raise exception 'ORDER_NOT_APPROVED'; end if;
      return new;
    end;
    $$;
    create trigger fixture_market_guard_before_insert
    before insert on public.market_guard_fixture
    for each row execute function public.market_require_approved_seller();
    create trigger fixture_order_guard_before_update
    before update on public.market_guard_fixture
    for each row execute function public.market_require_approved_seller_for_order();
    grant update on public.market_guard_fixture to authenticated;
  `);
  const sql = fs.readFileSync(
    new URL('../../docs/integration/supabase-anon-trigger-permissions-staging-20261026.sql', import.meta.url),
    'utf8'
  );
  await db.exec(sql);
  const result = await db.query(`
    select has_function_privilege('anon','public.market_require_approved_seller()','execute') as anon_market,
           has_function_privilege('authenticated','public.market_require_approved_seller()','execute') as auth_market,
           has_function_privilege('anon','public.market_require_approved_seller_for_order()','execute') as anon_order,
           has_function_privilege('authenticated','public.market_require_approved_seller_for_order()','execute') as auth_order
  `);
  assert.deepEqual(Object.values(result.rows[0]), [false, false, false, false]);
  await db.exec('set role authenticated');
  await db.exec('insert into public.market_guard_fixture(allowed) values(true)');
  await assert.rejects(
    db.exec('insert into public.market_guard_fixture(allowed) values(false)'),
    /SELLER_NOT_APPROVED/
  );
  await assert.rejects(
    db.exec('update public.market_guard_fixture set allowed=false'),
    /ORDER_NOT_APPROVED/
  );
  await db.exec('update public.market_guard_fixture set allowed=true');
  await db.exec('reset role');
  console.log('PASS direct anonymous/authenticated trigger RPC grants removed; guarded Marketplace triggers still run');
} finally {
  await db.close();
}
