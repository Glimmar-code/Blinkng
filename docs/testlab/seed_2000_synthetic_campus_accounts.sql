-- These are synthetic fixtures, not auth.users or public.profiles. Simulated
-- likes/follows stay separate from feed_posts, post_likes, follows, post_views,
-- point_transactions and leaderboards. No avatar is stored.
-- Posting, commenting and outbound messaging are disabled by hard constraints.

create table if not exists private.blink_test_synthetic_accounts (
  id bigint generated by default as identity primary key,
  username text not null unique,
  full_name text not null,
  university text not null,
  faculty text not null,
  department text not null,
  bio text not null default '',
  avatar_url text default null check (avatar_url is null),
  can_like boolean not null default true check (can_like),
  can_follow boolean not null default true check (can_follow),
  can_post boolean not null default false check (not can_post),
  can_comment boolean not null default false check (not can_comment),
  can_send_messages boolean not null default false check (not can_send_messages),
  can_receive_messages boolean not null default true,
  leaderboard_points integer not null default 0 check (leaderboard_points = 0),
  is_test_only boolean not null default true check (is_test_only),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists private.blink_test_synthetic_interactions (
  id bigint generated by default as identity primary key,
  account_id bigint not null references private.blink_test_synthetic_accounts(id) on delete cascade,
  action_type text not null check (action_type in ('like', 'follow')),
  target_id uuid not null,
  created_at timestamptz not null default now(),
  unique (account_id, action_type, target_id)
);

alter table private.blink_test_synthetic_accounts enable row level security;
alter table private.blink_test_synthetic_interactions enable row level security;
revoke all on private.blink_test_synthetic_accounts from public, anon, authenticated, service_role;
revoke all on private.blink_test_synthetic_interactions from public, anon, authenticated, service_role;

